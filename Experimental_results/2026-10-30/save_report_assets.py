#!/usr/bin/env python3
"""10/30代表資料を原バイトのまま複製。画像変換・描画は行わない。"""
import hashlib
import json
from pathlib import Path
import shutil

DAY = Path(__file__).resolve().parent
OUTPUT = DAY / "report_assets"
SOURCES = (
    ("live_r02_raw_f000635.png", DAY / "live_frame_evidence_r01/analysis_r02/evidence/decoded_f860e50d1c4e485a98cbc1a2f6138cdf_f000635.png",
     "native decoded PNG, session f860e50d1c4e485a98cbc1a2f6138cdf, frame 635, 1280x720; no annotations"),
    ("support_candidate_timeline.png", DAY / "cone_support_live_review_r01/results_r02/candidate_timeline.png",
     "numeric graph; source frame_review.csv, generated by cone_support_live_review_r01/analyze.py"),
    ("fixed_floor_height_sensitivity.png", DAY / "floor_pose_fixed_mode_r01/evaluation_r01/height_sensitivity.png",
     "numeric graph; source height_sensitivity.csv, generated by floor_pose_fixed_mode_r01/evaluate.py"),
)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    OUTPUT.mkdir(exist_ok=False)
    rows = []
    for name, source, meaning in SOURCES:
        target = OUTPUT / name
        shutil.copyfile(source, target)
        assert sha(source) == sha(target)
        rows.append(dict(file=name, source=str(source), sha256=sha(target), meaning=meaning, source_bytes_edited=False))
    (OUTPUT / "manifest.json").write_text(json.dumps(rows, indent=2)+"\n")
    print("Copied and hash-verified", len(rows), "assets")


if __name__ == "__main__":
    main()
